    private static int c_wcwidth(int charCode) {
        if (charCode < 0xFF) {
            if (((charCode + 1) & 0x7F) >= 0x21) return 1;
            else if (charCode > 0) return -1;
            else return 0;
        } else if ((charCode & 0xfffeffff) < 0xfffe) {
            if (((table[table[charCode >> 8] * 32 + ((charCode & 0xFF) >> 3)] >> (charCode & 7)) & 1) == 1) return 0;
            else if (((wtable[wtable[charCode >> 8] * 32 + ((charCode & 0xFF) >> 3)] >> (charCode & 7)) & 1) == 1) return 2;
            else return 1;
        } else if ((charCode & 0xfffe) == 0xfffe) return -1;
        else if ((charCode - 0x20000) < 0x20000) return 2;
        else if ((charCode == 0xe0001) || ((charCode - 0xe0020) < 0x5f) || ((charCode - 0xe0100) < 0xef)) return 0;
        else return 1;
    }

    static {
        OpenComputers.log.info("Initializing unicode wcwidth.");
        for (int i = 0; i < codepoint_limit; i++) {
            if (c_wcwidth(i) == 2)
                defined_double_wide.set(i);
        }
        try {
            OpenComputers.log.info("Initializing font glyph widths.");
            final InputStream font = FontUtils.class.getResourceAsStream("/assets/opencomputers/font.hex");
            try {
                String line;
                final BufferedReader input = new BufferedReader(new InputStreamReader(font, StandardCharsets.UTF_8));
                int out_of_range_glyph = 0;
                while ((line = input.readLine()) != null) {
                    final String[] info = line.split(":");
                    final int charCode = Integer.parseInt(info[0], 16);
                    if (charCode >= 0 && charCode < codepoint_limit) {
                        final int n = info[1].trim().length();
                        switch (n) {
                            case 64:
                                defined_double_wide.set(charCode);
                                break;
                            case 32:
                                defined_double_wide.clear(charCode);
                                break;
                            default:
                                OpenComputers.log.warn("Invalid glyph size detected in font.hex. Expected 64 or 32, got: " + n);
                                break;
                        }
                    } else {
                        if (out_of_range_glyph == 0) {
                            OpenComputers.log.warn(String.format("Invalid glyph char code detected in font.hex. Expected 0<= charCode <%X, got: %X", codepoint_limit, charCode));
                        }
                        out_of_range_glyph += 1;
                    }
                }
                if (out_of_range_glyph > 1) {
                    OpenComputers.log.warn(out_of_range_glyph + " total invalid glyph char codes detected in font.hex");
                }
            } finally {
                try {
                    font.close();
                } catch (Throwable ex) {
                    OpenComputers.log.error("Error closing font.hex: " + ex);
                }
            }
        } catch (Throwable ex) {
            OpenComputers.log.error("Error parsing glyphs to determine widths: " + ex);
        }
        OpenComputers.log.info("glyph width ready.");
    }
